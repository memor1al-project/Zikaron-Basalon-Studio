#!/usr/bin/env node
/**
 * Builds, deploys, and records the deployment.
 *
 * Doing these as one command is the point: a build number that has to be bumped by hand
 * drifts from what's live, and a changelog updated separately from the deploy ends up
 * describing a release that never shipped. Here the number, the release notes and the
 * deployment log can only move together.
 *
 * Usage:
 *   node scripts/release.mjs              # build, deploy, record
 *   node scripts/release.mjs --dry-run    # everything except the deploy
 */

import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import fs from "node:fs";
import path from "node:path";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const BUILD_NUMBER_FILE = path.join(ROOT, "app/build-number.json");
const RELEASES_DIR = path.join(ROOT, "app/src/releases");
const CURRENT_FILE = path.join(RELEASES_DIR, "current.json");
const FEATURES_FILE = path.join(RELEASES_DIR, "features.json");
const DEPLOYMENTS_FILE = path.join(ROOT, "docs/deployments.json");
const RELEASES_DOC = path.join(ROOT, "docs/RELEASES.md");

const DRY_RUN = process.argv.includes("--dry-run");

const readJson = (file) => JSON.parse(fs.readFileSync(file, "utf8"));
const writeJson = (file, value) => fs.writeFileSync(file, JSON.stringify(value, null, 2) + "\n");

/** Release files are named by version, so sorting them numerically gives the newest. */
function allReleases() {
  return fs
    .readdirSync(RELEASES_DIR)
    .filter((f) => /^\d+\.\d+\.\d+\.json$/.test(f))
    .map((f) => readJson(path.join(RELEASES_DIR, f)))
    .sort((a, b) => compareVersions(b.version, a.version));
}

function compareVersions(a, b) {
  const left = a.split(".").map(Number);
  const right = b.split(".").map(Number);
  for (let i = 0; i < 3; i++) {
    if ((left[i] ?? 0) !== (right[i] ?? 0)) return (left[i] ?? 0) - (right[i] ?? 0);
  }
  return 0;
}

/** Regenerates the human-readable changelog from the release files and the deploy log. */
function writeReleasesDoc(releases, deployments) {
  const deployedAt = new Map();
  for (const d of deployments) {
    // First deploy of a version is the one worth quoting as its release date.
    if (!deployedAt.has(d.version)) deployedAt.set(d.version, d);
  }

  const lines = [
    "# Releases",
    "",
    "Generated by `scripts/release.mjs` — edit `app/src/releases/` rather than this document:",
    "`features.json` for what the Studio does, `<version>.json` for what each release changed.",
    "",
    "The running version and build number are shown in the app's sidebar; clicking them",
    "opens the same notes in a panel.",
    "",
  ];

  // The full picture first: a changelog alone never says what the thing actually does.
  if (fs.existsSync(FEATURES_FILE)) {
    const features = readJson(FEATURES_FILE);
    lines.push(`## Everything in v${releases[0].version}`, "");
    for (const section of features.sections ?? []) {
      lines.push(`### ${section.title}`, "");
      for (const item of section.items) lines.push(`- ${item}`);
      lines.push("");
    }
    lines.push("---", "", "## Release history", "");
  }

  for (const release of releases) {
    const deploy = deployedAt.get(release.version);
    lines.push(`## v${release.version} — ${release.title}`);
    lines.push("");
    lines.push(
      deploy
        ? `*${release.date} · first deployed as build ${deploy.build} on ${deploy.deployedAt.slice(0, 16).replace("T", " ")}*`
        : `*${release.date} · not yet deployed*`
    );
    lines.push("");
    for (const change of release.changes) lines.push(`- ${change}`);
    lines.push("");
  }

  lines.push("## Deployment log");
  lines.push("");
  lines.push("| Build | Version | Deployed |");
  lines.push("|---|---|---|");
  for (const d of [...deployments].reverse()) {
    lines.push(`| ${d.build} | v${d.version} | ${d.deployedAt.slice(0, 16).replace("T", " ")} |`);
  }
  lines.push("");

  fs.writeFileSync(RELEASES_DOC, lines.join("\n"));
}

function main() {
  const releases = allReleases();
  if (releases.length === 0) throw new Error("No release files in app/src/releases/");
  const version = releases[0].version;

  // The app reads its version from here, so it can never disagree with the notes shipped.
  writeJson(CURRENT_FILE, { version });

  const buildFile = readJson(BUILD_NUMBER_FILE);
  const build = buildFile.build + 1;
  writeJson(BUILD_NUMBER_FILE, { ...buildFile, build });

  // Refreshed before every build so docs/i18n always describes what actually shipped.
  // Reporting, not gating: a half-translated screen is better live than blocked, and
  // the count in the output says plainly how much is still English.
  execFileSync("node", [path.join(ROOT, "scripts/i18n-catalog.mjs")], { stdio: "inherit" });

  console.log(`Building v${version}, build ${build} ...`);
  execFileSync("npm", ["--prefix", path.join(ROOT, "app"), "run", "build"], { stdio: "inherit" });

  if (DRY_RUN) {
    console.log("Dry run — skipping deploy. Build number was still incremented.");
  } else {
    console.log("Deploying ...");
    try {
      execFileSync("firebase", ["deploy", "--only", "hosting"], { cwd: ROOT, stdio: "inherit" });
    } catch (error) {
      // Give the number back. A failed deploy that still consumes one leaves a gap in the
      // log and, worse, a build number that was never live — which is exactly the thing
      // the log exists to let someone trust.
      writeJson(BUILD_NUMBER_FILE, { ...buildFile, build: buildFile.build });
      console.error(
        `\nDeploy failed, so build ${build} was not recorded and the number is free again.\n` +
          `If the error above mentions credentials, run:  firebase login --reauth\n`
      );
      throw error;
    }
  }

  const deployments = fs.existsSync(DEPLOYMENTS_FILE) ? readJson(DEPLOYMENTS_FILE) : [];
  deployments.push({
    build,
    version,
    deployedAt: new Date().toISOString(),
    title: releases[0].title,
    dryRun: DRY_RUN || undefined,
  });
  fs.mkdirSync(path.dirname(DEPLOYMENTS_FILE), { recursive: true });
  writeJson(DEPLOYMENTS_FILE, deployments);

  writeReleasesDoc(releases, deployments);

  console.log(`\nRecorded build ${build} of v${version}.`);
  console.log(`  ${path.relative(ROOT, DEPLOYMENTS_FILE)}`);
  console.log(`  ${path.relative(ROOT, RELEASES_DOC)}`);
}

main();
